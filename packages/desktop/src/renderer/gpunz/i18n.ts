export type GzKey = keyof typeof ru

export function gzT(locale: string | undefined) {
  const dict = locale?.toLowerCase().startsWith("ru") ? ru : en
  return (key: GzKey, vars?: Record<string, string | number>) => {
    let text: string = dict[key] ?? en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v))
    return text
  }
}

/** Money of the account: kopecks of rubles, or 1/10 000 of a dollar. */
export function gzMoney(kop: number, currency: "RUB" | "USD", locale: string | undefined, digits?: number): string {
  const ruLocale = locale?.toLowerCase().startsWith("ru")
  if (currency === "USD") {
    const v = kop / 10_000
    return `$${v.toFixed(digits ?? (v < 10 ? 2 : 0))}`
  }
  const rub = kop / 100
  const d = digits ?? (rub < 100 && rub % 1 !== 0 ? 2 : 0)
  const text = rub.toLocaleString(ruLocale ? "ru-RU" : "en-US", { minimumFractionDigits: d, maximumFractionDigits: d })
  return `${text} ₽`
}

/** «12 мин», «1 ч 05 мин», «45 с» */
export function gzDuration(ms: number, locale: string | undefined): string {
  const ruLocale = locale?.toLowerCase().startsWith("ru")
  const s = Math.max(0, Math.round(ms / 1000))
  if (s < 60) return ruLocale ? `${s} с` : `${s}s`
  const m = Math.floor(s / 60)
  if (m < 60) return ruLocale ? `${m} мин` : `${m} min`
  const h = Math.floor(m / 60)
  const mm = String(m % 60).padStart(2, "0")
  return ruLocale ? `${h} ч ${mm} мин` : `${h} h ${mm} min`
}
